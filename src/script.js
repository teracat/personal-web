const menuGroups = document.querySelectorAll(".menu-group");
const viewButtons = document.querySelectorAll("[data-view]");
const tabs = document.querySelectorAll("[data-tab]");
const panels = document.querySelectorAll("[data-panel]");
const breadcrumb = document.querySelector("[data-breadcrumb]");
const languageOptions = document.querySelectorAll("[data-language]");
const aboutPanel = document.querySelector('[data-panel="about"]');
const explorer = document.querySelector(".explorer");
const explorerToggle = document.querySelector(".explorer-toggle");
const ideWindow = document.querySelector(".ide-window");
const maximizeControl = document.querySelector(".maximize-control");
const closeControl = document.querySelector(".close-control");
const closeScreen = document.querySelector("[data-close-screen]");
const reopenControl = document.querySelector(".open-window");
let activeView = "home";
let currentLanguage = "en";
let isWindowMaximized = false;

function closeMenus() {
  for (const group of menuGroups) {
    group.classList.remove("open");
    group.querySelector(".menu-trigger").setAttribute("aria-expanded", "false");
  }
}

function setWindowMaximized(maximized) {
  isWindowMaximized = maximized;
  document.body.classList.toggle("window-maximized", maximized);
  ideWindow.classList.toggle("is-maximized", maximized);
  maximizeControl.setAttribute("aria-pressed", String(maximized));
  const labelKey = maximized ? "window.restore" : "window.maximize";
  maximizeControl.dataset.i18nAria = labelKey;
  maximizeControl.setAttribute("aria-label", translations[currentLanguage][labelKey]);
}

function closeWindow() {
  setWindowMaximized(false);
  ideWindow.hidden = true;
  closeScreen.hidden = false;
  reopenControl.focus();
}

function reopenWindow() {
  closeScreen.hidden = true;
  ideWindow.hidden = false;
  closeControl.focus();
}

function setExplorerCollapsed(collapsed) {
  explorer.classList.toggle("is-collapsed", collapsed);
  explorerToggle.setAttribute("aria-expanded", String(!collapsed));
  explorerToggle.dataset.i18nAria = collapsed ? "me.expandExplorer" : "me.collapseExplorer";
  explorerToggle.setAttribute("aria-label", translations[currentLanguage][explorerToggle.dataset.i18nAria]);
  explorerToggle.querySelector("span").textContent = collapsed ? "›" : "‹";
}

function wrapText(text, maxLength = 96) {
  const words = text.split(/\s+/);
  const lines = [];
  let line = "";

  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (candidate.length > maxLength && line) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }

  if (line) lines.push(line);
  return lines;
}

function renderAbout(language) {
  const fragment = document.createDocumentFragment();
  const addLine = (text) => {
    const line = document.createElement("div");
    line.className = "line";

    if (text === null) {
      line.classList.add("blank");
    } else {
      const comment = document.createElement("span");
      comment.className = "comment";
      comment.textContent = text;
      line.append(comment);
    }

    fragment.append(line);
  };

  addLine("/*");
  translations[language].paragraphs.forEach((paragraph, index) => {
    for (const wrappedLine of wrapText(paragraph)) addLine(` * ${wrappedLine}`);
    if (index < translations[language].paragraphs.length - 1) addLine(null);
  });
  addLine(" */");
  aboutPanel.replaceChildren(fragment);
}

function renderHomeSummary(language) {
  const container = document.querySelector("[data-home-summary]");
  const fragment = document.createDocumentFragment();
  const addTextLine = (text) => {
    const line = document.createElement("div");
    line.className = "line doc-comment";
    const comment = document.createElement("span");
    comment.className = "comment";
    comment.textContent = text;
    line.append(comment);
    fragment.append(line);
  };

  addTextLine("/// <summary>");
  addTextLine(`/// ${translations[language]["home.summary.1"]}`);

  const seeLine = document.createElement("div");
  seeLine.className = "line doc-comment";
  const prefix = document.createElement("span");
  prefix.className = "comment";
  prefix.textContent = `/// ${translations[language]["home.summary.2"]} <see href=\"`;
  const aboutLink = document.createElement("a");
  aboutLink.className = "comment doc-link";
  aboutLink.href = "#about";
  aboutLink.dataset.openView = "about";
  aboutLink.textContent = translations[language]["filename.about"];
  const suffix = document.createElement("span");
  suffix.className = "comment";
  suffix.textContent = '" />';
  seeLine.append(prefix, aboutLink, suffix);
  fragment.append(seeLine);
  addTextLine("/// </summary>");
  container.replaceChildren(fragment);
}

function applyLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translated = dictionary[element.dataset.i18n];
    if (translated) element.textContent = translated;
  });

  document.querySelectorAll("[data-code]").forEach((element) => {
    const translated = dictionary[`code.${element.dataset.code}`];
    if (translated) element.textContent = translated;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const translated = dictionary[element.dataset.i18nAria];
    if (translated) element.setAttribute("aria-label", translated);
  });

  for (const option of languageOptions) {
    const isSelected = option.dataset.language === language;
    option.setAttribute("aria-checked", String(isSelected));
    option.querySelector("small").textContent = isSelected ? "✓" : "";
  }

  document.querySelector('meta[name="description"]').content = `${dictionary["me.role1"]} — Jordi Badia Santaulària, teracat.com.`;
  renderHomeSummary(language);
  renderAbout(language);
  breadcrumb.textContent = dictionary[`breadcrumb.${activeView}`];
  document.title = `teracat.com — Jordi Badia Santaulària`;
  setExplorerCollapsed(explorer.classList.contains("is-collapsed"));
  setWindowMaximized(isWindowMaximized);
  closeMenus();
}

function showView(viewName) {
  activeView = viewName;

  for (const panel of panels) panel.hidden = panel.dataset.panel !== viewName;
  for (const tab of tabs) {
    const isActive = tab.dataset.tab === viewName;
    tab.classList.toggle("active-tab", isActive);
    tab.setAttribute("aria-selected", String(isActive));
  }

  breadcrumb.textContent = translations[currentLanguage][`breadcrumb.${viewName}`];
  closeMenus();
}

for (const group of menuGroups) {
  const trigger = group.querySelector(".menu-trigger");
  trigger.addEventListener("click", () => {
    const willOpen = !group.classList.contains("open");
    closeMenus();
    group.classList.toggle("open", willOpen);
    trigger.setAttribute("aria-expanded", String(willOpen));
  });
}

maximizeControl.addEventListener("click", () => {
  setWindowMaximized(!isWindowMaximized);
});
closeControl.addEventListener("click", closeWindow);
reopenControl.addEventListener("click", reopenWindow);

for (const button of viewButtons) {
  button.addEventListener("click", () => {
    if (button.dataset.view === "about") document.querySelector('[data-tab="about"]').hidden = false;
    showView(button.dataset.view);
  });
}

for (const tab of tabs) {
  tab.addEventListener("click", () => {
    if (tab.dataset.tab === "about") document.querySelector('[data-tab="about"]').hidden = false;
    showView(tab.dataset.tab);
  });
}

for (const option of languageOptions) {
  option.addEventListener("click", () => {
    currentLanguage = option.dataset.language;
    try { localStorage.setItem("teracat-language", currentLanguage); } catch { /* Storage is optional. */ }
    applyLanguage(currentLanguage);
  });
}

explorerToggle.addEventListener("click", () => {
  setExplorerCollapsed(!explorer.classList.contains("is-collapsed"));
});

document.querySelectorAll(".tree-parent").forEach((parent) => {
  parent.addEventListener("click", () => {
    const branch = parent.closest(".tree-branch");
    const expanded = parent.getAttribute("aria-expanded") === "true";
    parent.setAttribute("aria-expanded", String(!expanded));
    branch.classList.toggle("is-collapsed", expanded);
  });
});

document.addEventListener("click", (event) => {
  const aboutLink = event.target.closest("[data-open-view=\"about\"]");
  if (aboutLink) {
    event.preventDefault();
    showView("about");
  }

  if (!event.target.closest(".menu-group")) closeMenus();
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenus();
});
document.querySelectorAll("[data-year]").forEach((element) => {
  element.textContent = new Date().getFullYear();
});

const browserLanguage = [...(navigator.languages || []), navigator.language || ""]
  .map((language) => language.toLowerCase().split("-")[0])
  .find((language) => Object.prototype.hasOwnProperty.call(translations, language)) || "en";

try {
  const savedLanguage = localStorage.getItem("teracat-language");
  if (savedLanguage && Object.prototype.hasOwnProperty.call(translations, savedLanguage)) currentLanguage = savedLanguage;
  else currentLanguage = browserLanguage;
} catch {
  currentLanguage = browserLanguage;
}

isWindowMaximized = window.matchMedia("(max-width: 1024px)").matches;
setExplorerCollapsed(window.matchMedia("(max-width: 760px)").matches);
applyLanguage(currentLanguage);
window.matchMedia("(max-width: 760px)").addEventListener("change", (event) => {
  setExplorerCollapsed(event.matches);
});
